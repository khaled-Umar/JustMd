// Bundles the ProseMirror edit-mode engine into the files the page loads.
//
//   cd tools/editor && npm ci && npm run build
//
// Outputs (paths relative to the repo root, both committed; dotnet build never runs node):
//   src/JustMd/web/vendor/editor.bundle.js   IIFE exposing window.JustMdEditor
//   src/JustMd/web/vendor/editor.css         the ProseMirror, tables and gap cursor stylesheets
//
// `npm run build -- --check` builds in memory and fails unless the files on disk match byte for byte.
// The root .gitattributes marks them -text so core.autocrlf cannot rewrite them on checkout.

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const vendor = resolve(here, '..', '..', 'src', 'JustMd', 'web', 'vendor');
const check = process.argv.includes('--check');

const STYLESHEETS = [
  'prosemirror-view/style/prosemirror.css',
  'prosemirror-tables/style/tables.css',
  'prosemirror-gapcursor/style/gapcursor.css',
];

const readPackage = async (name) =>
  JSON.parse(await readFile(join(here, 'node_modules', name, 'package.json'), 'utf8'));

const describePackage = async (name) => {
  const { version, license } = await readPackage(name);
  return `${name} ${version} (${license})`;
};

// One description per package the bundle really contains.
async function bundledPackages(inputs) {
  const names = new Set();
  for (const input of Object.keys(inputs)) {
    const match = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input.replaceAll('\\', '/'));
    if (match) names.add(match[1]);
  }
  return Promise.all([...names].sort().map(describePackage));
}

const banner = (subject, packages) =>
  `/*! ${subject}. Generated by tools/editor, do not edit. Bundled: ${packages.join(', ')}. See THIRD-PARTY-NOTICES.md. */\n`;

async function buildScript() {
  const result = await build({
    absWorkingDir: here,
    entryPoints: ['src/index.js'],
    bundle: true,
    format: 'iife',
    globalName: 'JustMdEditor',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    metafile: true,
    write: false,
    logLevel: 'warning',
  });
  return banner('JustMd editor bundle', await bundledPackages(result.metafile.inputs)) + result.outputFiles[0].text;
}

async function buildStyles() {
  const packages = await Promise.all(STYLESHEETS.map((file) => describePackage(file.split('/')[0])));
  const parts = await Promise.all(STYLESHEETS.map((file) => readFile(join(here, 'node_modules', file), 'utf8')));
  return `${banner('JustMd editor styles', packages)}${parts.map((css) => css.replace(/\r\n/g, '\n').trim()).join('\n\n')}\n`;
}

const outputs = [
  ['editor.bundle.js', await buildScript()],
  ['editor.css', await buildStyles()],
];

let stale = false;
for (const [name, content] of outputs) {
  const path = join(vendor, name);
  const size = Buffer.byteLength(content);
  if (check) {
    const committed = await readFile(path).catch(() => null);
    if (committed?.equals(Buffer.from(content))) {
      console.log(`${name} is up to date (${size} bytes)`);
    } else {
      console.error(`${name} is out of date: run npm run build in tools/editor`);
      stale = true;
    }
  } else {
    await writeFile(path, content);
    console.log(`${name}: ${size} bytes`);
  }
}
if (stale) process.exit(1);
